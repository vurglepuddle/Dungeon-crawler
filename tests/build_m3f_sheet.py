"""Current muted UI captures; historical M3d frames are clearly labelled."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'build/m3f_shots'
font=ImageFont.truetype(str(ROOT/'assets/font/vetka.ttf'),16)
frames=[
 ('M3d upper UI / before','m3d_shots','02_room'),
 ('M3f / warm upper UI','m3f_shots','01_upper_materials'),
 ('Equipped: DROP / pack','m3f_shots','02_equipped_drop_card'),
 ('Equipped knife dropped','m3f_shots','03_equipment_dropped'),
 ('Loose icons on leather','m3f_shots','08_filled_pack_tray'),
 ('Brighter item brackets','m3f_shots','08_bright_place_brackets'),
 ('Two keys / one vial','m3f_shots','21_two_belt_keys'),
 ('Which gate?','m3f_shots','21_key_gate_card'),
 ('Gate corner / no fake arch','m3f_shots','15_f1_gate_direction_0'),
 ('M3d stair / before','m3d_shots','07_stairs_down'),
 ('Marked stairs / FORWARD','m3f_shots','20_stairs_forward'),
 ('Working lift / FORWARD','m3f_shots','22_lift_working_forward'),
 ('M3d dead lift / before','m3d_shots','05_lift_dead'),
 ('Shut lift / bump explains','m3f_shots','06_lift_explained'),
 ('Lever head-on / up','m3f_shots','09_lever_head_on_up'),
 ('Lever head-on / down','m3f_shots','10_lever_head_on_down'),
 ('Porter / no buried loot','m3f_shots','14_porter_clear_floor'),
 ('Stone on flush plate','m3f_shots','11_stone_on_plate'),
 ('Torn ink map','m3f_regression_shots','09_ink_map'),
 ('Sparse crate / no loot','m3f_shots','12_prop_crate'),
 ('Solid-wall pilaster','m3f_shots','12_prop_pillar'),
 ('Painted title / logo','m3f_shots','00_title'),
 ('Death plate','m3f_regression_shots','16_death_plate'),
 ('Home by forward tap','m3f_shots','24_owner_home'),
]
sheet=Image.new('RGB',(154*4,362*6),'#0c101c')
draw=ImageDraw.Draw(sheet)
for i,(caption,directory,name) in enumerate(frames):
    path=ROOT/'build'/directory/(name+'.png')
    if not path.exists():
        # Historical captures are optional on a clean checkout; current
        # captures can be regenerated by the included muted runner.
        if directory!='m3d_shots': raise FileNotFoundError(path)
        continue
    x=i%4*154; y=i//4*362
    frame=Image.open(path).convert('RGB').resize((154,342),Image.Resampling.NEAREST)
    sheet.paste(frame,(x,y+20));draw.text((x+2,y),caption,font=font,fill='#d3c8a4')
sheet.save(OUT/'m3f_sheet_native.png')
sheet.resize((sheet.width*2,sheet.height*2),Image.Resampling.NEAREST).save(OUT/'m3f_sheet_2x.png')
print('24 labelled panels; actual M3f taps and three historical M3d comparisons.')
